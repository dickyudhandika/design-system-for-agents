#!/usr/bin/env python3
"""ds4a resolve — merge core + tone pack + project overlay into DESIGN.md.

Layers (later wins on tokens):
  library/core.md            tone-free contracts and guardrails, written with {{placeholders}}
  library/tones/<tone>.md    token values + tone-only prose
  <project>/.ds4a/project.md overlay: `tone:`, `type:`, token overrides, project notes

Usage:
  python3 scripts/resolve.py --project . [--tone warm-sharp] [--type dashboard]
  python3 scripts/resolve.py --list-tones
  python3 scripts/resolve.py --project . --check        # report only, write nothing
  python3 scripts/resolve.py --tone neutral --stdout    # no project needed

Standard library only.
"""
import argparse
import re
import sys
from pathlib import Path

SKILL_DIR = Path(__file__).resolve().parent.parent
MARKER = "Generated by ds4a resolve"

SECTION_ORDER = [
    "Overview", "Colors", "Typography", "Layout", "Elevation & Depth",
    "Shapes", "Components", "Do's and Don'ts", "Pre-flight Checklist",
]
# Sections where the tone's content reads first (tokens, then rules); others read core first.
TONE_FIRST = {"Overview", "Colors", "Typography", "Layout", "Elevation & Depth", "Shapes"}
REQUIRED_COLORS = [
    "background", "foreground", "secondary", "muted", "border",
    "muted-foreground", "primary", "primary-foreground", "destructive",
]
PH = re.compile(r"\{\{\s*([^{}]+?)\s*\}\}")


class ResolveError(Exception):
    pass


# ───────────────────────── minimal YAML subset ─────────────────────────

class Leaf:
    __slots__ = ("value", "pad", "comment", "block")

    def __init__(self, value, pad="", comment="", block=None):
        self.value, self.pad, self.comment, self.block = value, pad, comment, block


class Comment:
    __slots__ = ("text",)

    def __init__(self, text):
        self.text = text


_uid = [0]


def _next_uid():
    _uid[0] += 1
    return _uid[0]


def split_comment(rest):
    """Split `value   # comment` honoring quotes. Returns (value, pad, comment)."""
    quote = None
    i = 0
    while i < len(rest):
        ch = rest[i]
        if quote:
            if ch == "\\" and quote == '"':
                i += 2
                continue
            if ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
        elif ch == "#" and (i == 0 or rest[i - 1] in " \t"):
            before = rest[:i]
            value = before.rstrip()
            return value, before[len(value):], rest[i:]
        i += 1
    return rest.rstrip(), "", ""


def parse_yaml(lines):
    root = {}
    stack = [(-1, root)]
    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        if not line.strip():
            continue
        indent = len(line) - len(line.lstrip(" "))
        s = line.strip()
        while len(stack) > 1 and stack[-1][0] >= indent:
            stack.pop()
        parent = stack[-1][1]
        if s.startswith("#"):
            parent[f"#c{_next_uid()}"] = Comment(s)
            continue
        m = re.match(r"^([A-Za-z0-9_.\-]+):(?:[ \t]+(.*))?$", s)
        if not m:
            raise ResolveError(f"unsupported YAML line: {line!r}")
        key, rest = m.group(1), (m.group(2) or "")
        value, pad, comment = split_comment(rest)
        if value == "":
            parent[key] = {}
            stack.append((indent, parent[key]))
        elif value in (">", ">-", "|", "|-"):
            block = []
            while i < len(lines) and (not lines[i].strip() or len(lines[i]) - len(lines[i].lstrip(" ")) > indent):
                block.append(lines[i].strip())
                i += 1
            while block and not block[-1]:
                block.pop()
            joined = (" " if value.startswith(">") else "\n").join(block)
            parent[key] = Leaf(joined, block=(value, block))
        else:
            parent[key] = Leaf(value, pad, comment)
    return root


def emit_yaml(node, indent=0):
    out = []
    pre = " " * indent
    for k, v in node.items():
        if isinstance(v, Comment):
            out.append(pre + v.text)
        elif isinstance(v, dict):
            out.append(f"{pre}{k}:")
            out.extend(emit_yaml(v, indent + 2))
        elif v.block:
            ind, blines = v.block
            out.append(f"{pre}{k}: {ind}")
            out.extend(f"{pre}  {b}" for b in blines)
        else:
            out.append(f"{pre}{k}: {v.value}{v.pad}{v.comment}")
    return out


def strip_comments(node):
    return {k: strip_comments(v) if isinstance(v, dict) else v
            for k, v in node.items() if not isinstance(v, Comment)}


def merge(dst, src):
    for k, v in src.items():
        if isinstance(v, dict) and isinstance(dst.get(k), dict):
            merge(dst[k], v)
        else:
            dst[k] = v


def unquote(v):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] == '"':
        return v[1:-1].replace('\\"', '"').replace("\\\\", "\\")
    if len(v) >= 2 and v[0] == v[-1] == "'":
        return v[1:-1]
    return v


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lookup(tree, path):
    cur = tree
    for part in path.split("."):
        if not isinstance(cur, dict) or part not in cur:
            raise KeyError(path)
        cur = cur[part]
    return cur


def resolve_value(tree, path, stack=()):
    """Raw (still-quoted) value at `path`, following {{refs}} inside YAML values."""
    node = lookup(tree, path)
    if isinstance(node, (dict, Comment)):
        raise KeyError(path)
    if "{{" not in node.value:
        return node.value
    if path in stack:
        raise ResolveError(f"circular token reference at {path}")
    inner = unquote(node.value)
    whole = PH.fullmatch(inner.strip())
    if whole:
        return resolve_value(tree, whole.group(1), stack + (path,))
    return quote(PH.sub(lambda m: unquote(resolve_value(tree, m.group(1), stack + (path,))), inner))


def resolve_tree(tree):
    """Return a copy of `tree` with every {{ref}} inside YAML values resolved."""
    def walk(node, prefix):
        out = {}
        for k, v in node.items():
            if isinstance(v, dict):
                out[k] = walk(v, prefix + [k])
            elif isinstance(v, Leaf) and "{{" in v.value and not v.block:
                path = ".".join(prefix + [k])
                try:
                    val = resolve_value(tree, path)
                except KeyError as e:
                    raise ResolveError(f"token {path} references missing token {e.args[0]}")
                out[k] = Leaf(val, v.pad, v.comment)
            else:
                out[k] = v
        return out
    return walk(tree, [])


# ───────────────────────── markdown layers ─────────────────────────

def read_layer(path):
    text = Path(path).read_text(encoding="utf-8")
    if not text.startswith("---"):
        raise ResolveError(f"{path}: missing YAML frontmatter")
    lines = text.split("\n")
    end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if end is None:
        raise ResolveError(f"{path}: unterminated frontmatter")
    fm = parse_yaml(lines[1:end])
    return fm, "\n".join(lines[end + 1:]), text


def split_sections(body):
    sections, cur, buf = {}, None, []
    for line in body.split("\n"):
        m = re.match(r"^## (.+?)\s*$", line)
        if m:
            if cur is not None:
                sections[cur] = "\n".join(buf).strip("\n")
            cur, buf = m.group(1), []
        elif cur is not None:
            buf.append(line)
    if cur is not None:
        sections[cur] = "\n".join(buf).strip("\n")
    return sections


def leaf_text(fm, key, default=""):
    v = fm.get(key)
    return unquote(v.value) if isinstance(v, Leaf) else default


# ───────────────────────── project-type matrix ─────────────────────────

def norm(name):
    return re.sub(r"[^a-z0-9]", "", name.lower())


def load_matrix(path):
    comp, layout, types = {}, {}, []
    target = None
    for line in Path(path).read_text(encoding="utf-8").split("\n"):
        if not line.startswith("|"):
            target = None
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if cells[0] in ("Component", "Layout pattern"):
            target = comp if cells[0] == "Component" else layout
            hdr = cells[1:]
            if cells[0] == "Component":
                types = hdr
            continue
        if target is None or set(cells[0]) <= set("-: "):
            continue
        if cells[0] in ("Type",):
            target = None
            continue
        key = norm(cells[0]) if target is comp else cells[0]
        target[key] = {t: ("✅" in c) for t, c in zip(types, cells[1:])}
    return comp, layout, types


def filter_components(body, ptype, comp):
    parts = re.split(r"(?m)^(?=### )", body)
    keep = []
    for part in parts:
        m = re.match(r"### (.+?)(?:\s*\(grown\))?\s*$", part.split("\n", 1)[0])
        if m and norm(m.group(1)) in comp and not comp[norm(m.group(1))].get(ptype, True):
            continue
        keep.append(part)
    return "".join(keep)


def filter_layout(body, ptype, layout):
    out = []
    for line in body.split("\n"):
        m = re.match(r"^<!--layout:(.+?)-->", line)
        if m:
            row = layout.get(m.group(1).strip())
            line = line[m.end():]
            if ptype and row is not None and not row.get(ptype, True):
                continue
        out.append(line)
    return "\n".join(out)


# ───────────────────────── contrast ─────────────────────────

def _rgb(h):
    h = h.strip().lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    if len(h) not in (6, 8):
        return None
    try:
        return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
    except ValueError:
        return None


def _lum(rgb):
    def ch(v):
        v /= 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (ch(v) for v in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = _lum(a), _lum(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


CONTRAST_PAIRS = [
    ("foreground", "background", 4.5),
    ("muted-foreground", "background", 4.5),
    ("primary-foreground", "primary", 4.5),
    ("primary-foreground", "destructive", 4.5),
    ("primary", "background", 3.0),
]


def contrast_report(tree):
    colors = tree.get("colors", {})
    warns = []
    for fg, bg, need in CONTRAST_PAIRS:
        try:
            a = _rgb(unquote(colors[fg].value))
            b = _rgb(unquote(colors[bg].value))
        except (KeyError, AttributeError):
            continue
        if a and b:
            ratio = contrast(a, b)
            if ratio < need:
                warns.append(f"{fg} on {bg}: {ratio:.2f}:1 (needs {need}:1)")
    return warns


# ───────────────────────── resolve ─────────────────────────

def list_tones(lib):
    tones = []
    for p in sorted((lib / "tones").glob("*.md")):
        fm, _, _ = read_layer(p)
        desc = leaf_text(fm, "description").split(". ")[0]
        tones.append((p.stem, leaf_text(fm, "version", "?"), desc))
    return tones


def resolve(lib, tone, overlay_path, ptype):
    core_fm, core_body, _ = read_layer(lib / "core.md")
    tone_path = lib / "tones" / f"{tone}.md"
    if not tone_path.exists():
        names = ", ".join(t[0] for t in list_tones(lib))
        raise ResolveError(f"unknown tone '{tone}'. Available: {names}")
    tone_fm, tone_body, _ = read_layer(tone_path)

    tree = {}
    core_version = leaf_text(core_fm, "version", "?")
    for k in ("schema", "version"):
        core_fm.pop(k, None)
    merge(tree, core_fm)
    merge(tree, tone_fm)
    ov_sections = {}
    if overlay_path and Path(overlay_path).exists():
        ov_fm, ov_body, _ = read_layer(overlay_path)
        for k in ("tone", "type"):
            ov_fm.pop(k, None)
        merge(tree, strip_comments(ov_fm))
        ov_sections = {k: v for k, v in
                       ((k, re.sub(r"<!--.*?-->", "", v, flags=re.S).strip()) for k, v in split_sections(ov_body).items())
                       if v}
    tree = resolve_tree(tree)

    missing = set()

    def fill(text):
        def sub(m):
            expr = m.group(1)
            if expr == "extra:colors":
                rows = []
                for k, v in tree.get("colors", {}).items():
                    if k in REQUIRED_COLORS or not isinstance(v, Leaf):
                        continue
                    role = v.comment.lstrip("# ").strip() or "Project-specific token."
                    rows.append(f"| `{k}` | `{unquote(v.value)}` | {role} |")
                return "\n".join(rows)
            try:
                return unquote(resolve_value(tree, expr))
            except KeyError:
                missing.add(expr)
                return m.group(0)
        out = PH.sub(sub, text)
        # drop lines whose only content was an empty {{extra:...}} expansion
        return re.sub(r"\n\n+(?=\n)", "\n\n", out) if "extra:" in text else out

    core_s = {k: fill(v) for k, v in split_sections(core_body).items()}
    tone_s = {k: fill(v) for k, v in split_sections(tone_body).items()}
    ov_s = {k: fill(v) for k, v in ov_sections.items()}

    sections = []
    for name in SECTION_ORDER:
        c, t, o = core_s.get(name, ""), tone_s.get(name, ""), ov_s.get(name, "")
        if name == "Overview" and o:
            t, o = o, ""
        if o and not o.lstrip().startswith("### "):
            o = "### Project notes\n\n" + o
        parts = [t, c, o] if name in TONE_FIRST else [c, t, o]
        body = "\n\n".join(p.strip("\n") for p in parts if p.strip())
        if body:
            sections.append((name, body))

    if missing:
        raise ResolveError("unresolved placeholders (no tone defines them): " + ", ".join(sorted(missing)))

    comp, layout, types = load_matrix(SKILL_DIR / "references" / "component-matrix.md")
    if ptype and ptype not in types:
        raise ResolveError(f"unknown project type '{ptype}'. Valid: {', '.join(types)}")

    contracts = {norm(re.sub(r"\s*\(grown\)\s*$", "", h)) for h in
                 re.findall(r"(?m)^### (.+?)\s*$", dict(sections).get("Components", ""))}
    parity = [n for n in comp if n not in contracts]

    def render(filter_type):
        out = []
        for name, body in sections:
            if name == "Components" and filter_type:
                body = filter_components(body, filter_type, comp)
            if name == "Layout":
                body = filter_layout(body, filter_type, layout)
            out.append(f"## {name}\n\n{body.strip(chr(10))}\n")
        return "\n".join(out)

    fm_lines = ["---"] + emit_yaml(tree) + ["---"]
    body_text = render(ptype)
    chrome = len(fm_lines) + 8  # frontmatter + generated-header comment and spacing
    full_lines = chrome + len(render(None).split("\n"))
    total = chrome + len(body_text.split("\n"))
    layers = f"core v{core_version} + tone {tone} v{leaf_text(tone_fm, 'version', '?')}"
    if ov_sections or (overlay_path and Path(overlay_path).exists()):
        layers += " + project overlay"
    header = [
        "<!--",
        f"{MARKER} — do not edit by hand. Edit .ds4a/project.md or the tone, then run /ds4a resolve.",
        f"Layers: {layers}",
        f"Project type: {ptype or 'all components'}",
        f"Output: {total} lines ({round(100 * total / full_lines)}% of the full resolved library)",
        "-->",
    ]
    doc = "\n".join(fm_lines + [""] + header + [""]) + "\n" + body_text.rstrip("\n") + "\n"
    return doc, {"layers": layers, "lines": len(doc.split("\n")), "full": full_lines,
                 "contrast": contrast_report(tree), "parity": parity, "tree": tree, "tone": tone, "type": ptype}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project", default=".", help="project root (default: .)")
    ap.add_argument("--library", default=str(SKILL_DIR / "library"), help="library dir (default: skill's library/)")
    ap.add_argument("--tone", help="tone name (default: overlay `tone:` or neutral)")
    ap.add_argument("--type", dest="ptype", help="project type (default: overlay `type:` or all components)")
    ap.add_argument("--out", help="output path (default: <project>/DESIGN.md)")
    ap.add_argument("--stdout", action="store_true", help="print DESIGN.md instead of writing it")
    ap.add_argument("--check", action="store_true", help="report only; write nothing")
    ap.add_argument("--no-overlay", action="store_true", help="ignore .ds4a/project.md")
    ap.add_argument("--force", action="store_true", help="overwrite an existing DESIGN.md not generated by ds4a")
    ap.add_argument("--list-tones", action="store_true")
    args = ap.parse_args()

    lib = Path(args.library)
    try:
        if args.list_tones:
            for name, ver, desc in list_tones(lib):
                print(f"{name}\tv{ver}\t{desc}")
            return 0

        project = Path(args.project)
        overlay = None if args.no_overlay else project / ".ds4a" / "project.md"
        tone, ptype = args.tone, args.ptype
        if overlay and overlay.exists():
            ov_fm, _, _ = read_layer(overlay)
            tone = tone or leaf_text(ov_fm, "tone") or None
            ptype = ptype or leaf_text(ov_fm, "type") or None
        tone = tone or "neutral"

        doc, info = resolve(lib, tone, overlay, ptype)
    except ResolveError as e:
        print(f"ds4a resolve: {e}", file=sys.stderr)
        return 1

    if args.stdout:
        sys.stdout.write(doc)
    elif not args.check:
        out = Path(args.out) if args.out else project / "DESIGN.md"
        if out.exists() and not args.force and MARKER not in out.read_text(encoding="utf-8"):
            print(f"ds4a resolve: {out} exists and was not generated by ds4a; refusing to overwrite (use --force)",
                  file=sys.stderr)
            return 1
        out.write_text(doc, encoding="utf-8")
        print(f"wrote {out}", file=sys.stderr)
    print(f"{info['layers']} | {info['lines']} lines ({round(100 * info['lines'] / info['full'])}% of full)",
          file=sys.stderr)
    for w in info["contrast"]:
        print(f"WARNING contrast: {w}", file=sys.stderr)
    for n in info["parity"]:
        print(f"WARNING matrix parity: '{n}' is in component-matrix.md but has no contract in the library", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
