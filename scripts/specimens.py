#!/usr/bin/env python3
"""ds4a specimens — the project's real components, renderable in the preview.

A specimen is a static HTML/CSS copy of a component from this project, stored in
<project>/.ds4a/specimens/<slug>.html. It is a copy on purpose: the preview stays
one self-contained file with zero build integration. Values inside a specimen use
the same custom properties as the preview (var(--color-primary), var(--space-lg)),
so switching tone re-skins it.

Every specimen starts with a provenance header:

  <!-- ds4a:specimen
  title: Pill
  source: src/components/Pill.tsx
  captured: 2026-11-17
  contract: Button
  -->

`contract:` is optional. When it names a core contract, the preview shows the
specimen as that contract's project version (and the contract matrix says
"specimen" instead of "enforced").

Commands:
  python3 scripts/specimens.py --project . list
  python3 scripts/specimens.py --project . scan
  python3 scripts/specimens.py --project . add pill --from src/components/Pill.tsx
  python3 scripts/specimens.py --project . add pill --html /tmp/pill.html
  python3 scripts/specimens.py --project . remove pill

`scan` is the candidate finder used by `/ds4a diff`: component files with no
specimen and no matching core contract. It writes nothing.

Standard library only.
"""
import argparse
import json
import re
import subprocess
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import resolve as R  # noqa: E402

HEADER_RE = re.compile(r"^\s*<!--\s*ds4a:specimen(.*?)-->\s*", re.S)
CANDIDATE_ROOTS = ("src/components", "components", "app/components", "src/ui", "ui",
                   "src/sections", "src/blocks", "src/lib/components")
CANDIDATE_EXTS = {".tsx", ".jsx", ".astro", ".svelte", ".vue", ".html"}
SKIP_PARTS = {"node_modules", ".git", ".next", "dist", "build", ".ds4a", "coverage"}
MARKER = "Generated by ds4a apply"


def kebab(name):
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", name)
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def pretty(slug):
    words = [w for w in re.split(r"[-_\s]+", slug) if w]
    return " ".join(w[:1].upper() + w[1:] for w in words)


def contract_names(lib):
    """Every `### Name` contract in core, `(grown)` suffix removed."""
    body = R.split_sections(R.read_layer(lib / "core.md")[1]).get("Components", "")
    return [re.sub(r"\s*\(grown\)\s*$", "", h) for h in re.findall(r"(?m)^### (.+?)\s*$", body)]


def parse_header(text):
    """`<!-- ds4a:specimen key: value ... -->` -> (meta, body)."""
    m = HEADER_RE.match(text)
    if not m:
        return {}, text
    meta = {}
    for line in m.group(1).splitlines():
        line = line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        k, v = line.split(":", 1)
        meta[k.strip().lower()] = v.strip().strip("'\"")
    return meta, text[m.end():]


def spec_header(meta):
    lines = ["<!-- ds4a:specimen"]
    for k in ("title", "source", "captured", "contract"):
        if meta.get(k):
            lines.append(f"{k}: {meta[k]}")
    lines.append("-->")
    return "\n".join(lines)


def sanitize(text):
    """Specimens are trusted project copies, but never let them run script."""
    text = re.sub(r"<script\b.*?</script\s*>", "", text, flags=re.S | re.I)
    text = re.sub(r"<script\b[^>]*/>", "", text, flags=re.I)
    text = re.sub(r"\son[a-z]+\s*=\s*(\"[^\"]*\"|'[^']*'|[^\s>]+)", "", text, flags=re.I)
    return re.sub(r"javascript:", "", text, flags=re.I)


def source_status(project, meta):
    """None (no source), 'missing', 'changed' (source newer than capture), or 'ok'."""
    src = meta.get("source")
    if not src:
        return None
    p = (project / src).resolve()
    try:
        p.relative_to(project.resolve())
    except ValueError:
        return "missing"
    if not p.exists():
        return "missing"
    cap = meta.get("captured")
    if cap:
        try:
            captured = date.fromisoformat(cap)
        except ValueError:
            return "ok"
        if date.fromtimestamp(p.stat().st_mtime) > captured:
            return "changed"
    return "ok"


def load(project, registered=None):
    """Read .ds4a/specimens/*.html, ordered by the overlay list when present."""
    folder = project / ".ds4a" / "specimens"
    if not folder.exists():
        return []
    files = {p.stem: p for p in sorted(folder.glob("*.html"))}
    order = registered if registered is not None else sorted(files)
    out = []
    for slug in order:
        p = files.get(slug)
        if not p:
            continue
        text = p.read_text(encoding="utf-8", errors="ignore")
        meta, body = parse_header(text)
        out.append({"slug": slug, "file": p, "title": meta.get("title") or pretty(slug),
                    "source": meta.get("source", ""), "captured": meta.get("captured", ""),
                    "contract": meta.get("contract", ""), "status": source_status(project, meta),
                    "html": sanitize(body.strip())})
    return out


# ───────────────────────── JSX / template extraction ─────────────────────────

def _balanced(text, start, open_ch="(", close_ch=")"):
    depth, i, quote = 0, start, None
    while i < len(text):
        ch = text[i]
        if quote:
            if ch == "\\":
                i += 2
                continue
            if ch == quote:
                quote = None
        elif ch in "\"'`":
            quote = ch
        elif text.startswith("//", i):
            i = text.find("\n", i)
            if i < 0:
                return text[start:]
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            if end < 0:
                return text[start:]
            i = end + 1
        elif ch == open_ch:
            depth += 1
        elif ch == close_ch:
            depth -= 1
            if depth == 0:
                return text[start + 1:i]
        i += 1
    return text[start + 1:]


def _style_value(v):
    v = v.strip()
    if v.startswith("{"):
        return ""
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'`":
        v = v[1:-1]
    return v


def jsx_to_html(src, defaults=None):
    defaults = defaults or {}
    s = re.sub(r"\{/\*.*?\*/\}", "", src, flags=re.S)
    # style={{ ... }} -> style="kebab: value; ..."
    def style_obj(m):
        pairs = []
        for part in re.split(r",(?![^()]*\))", m.group(1)):
            if ":" not in part:
                continue
            k, v = part.split(":", 1)
            key = re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", k.strip()).lower()
            val = _style_value(v)
            if key and val:
                pairs.append(f"{key}:{val}")
        return f'style="{";".join(pairs)}"' if pairs else ""
    s = re.sub(r"style=\{\{([^{}]*)\}\}", style_obj, s)
    s = re.sub(r"className=(\{[^}]*\}|\"[^\"]*\"|'[^']*')",
               lambda m: "class=" + (m.group(1)[1:-1] if m.group(1).startswith("{") else m.group(1)), s)
    s = s.replace("htmlFor=", "for=").replace("tabIndex=", "tabindex=")
    s = re.sub(r"\son[A-Z]\w*=\{(?:[^{}]|\{[^{}]*\})*\}", "", s)
    s = re.sub(r"\{\.\.\.[^}]*\}", "", s)
    # A JS expression used as text: keep a literal, then a prop default, then the
    # identifier itself (so `{title}` reads as "Title" instead of disappearing).
    def expr(m):
        inner = m.group(1).strip()
        lit = re.fullmatch(r"[\"'`](.*?)[\"'`]", inner, re.S) or re.search(r"[\"'`](.*?)[\"'`]", inner, re.S)
        if lit:
            return lit.group(1)
        if re.fullmatch(r"[A-Za-z_$][\w$]*", inner):
            if inner in defaults:
                return defaults[inner]
            return "Content" if inner == "children" else inner[:1].upper() + inner[1:]
        return ""
    s = re.sub(r"\{([^{}]*)\}", expr, s)
    # Unknown components: drop the tag, keep children. Lowercase tags stay.
    s = re.sub(r"</?([A-Z][A-Za-z0-9_.]*)\b[^>]*>", "", s)
    # Fragments.
    s = s.replace("<>", "").replace("</>", "")
    # Self-closing lowercase tags -> HTML void handling.
    s = re.sub(r"<([a-z][a-z0-9-]*)\b([^>]*)/>",
               lambda m: f"<{m.group(1)}{m.group(2)}>" if m.group(1) in
               {"input", "img", "br", "hr", "source", "area", "base", "col", "embed", "link", "meta", "track", "wbr"}
               else f"<{m.group(1)}{m.group(2)}></{m.group(1)}>", s)
    return s.strip()


def extract_markup(text, suffix, defaults=None):
    if suffix == ".html":
        return text.strip()
    if suffix == ".astro":
        return re.sub(r"^---.*?---\s*", "", text, flags=re.S).strip()
    if suffix in (".vue", ".svelte"):
        parts = re.findall(r"<template\b[^>]*>(.*?)</template>", text, re.S)
        styles = re.findall(r"<style\b[^>]*>(.*?)</style>", text, re.S)
        return "\n".join(p.strip() for p in parts + [f"<style>{s.strip()}</style>" for s in styles] if p.strip())
    candidates = []
    for m in re.finditer(r"\breturn\s*\(", text):
        candidates.append(_balanced(text, m.end() - 1))
    for m in re.finditer(r"=>\s*\(", text):
        candidates.append(_balanced(text, m.end() - 1))
    if not candidates:
        m = re.search(r"\breturn\s*(<)", text)
        if m:
            tail = text[m.start(1):]
            end = tail.rfind(";")
            candidates.append(tail[:end] if end > 0 else tail)
    if not candidates:
        m = re.search(r"=>\s*(<)", text)
        if m:
            tail = text[m.start(1):]
            end = tail.rfind(";")
            candidates.append(tail[:end] if end > 0 else tail)
    if not candidates:
        return ""
    return jsx_to_html(max(candidates, key=len), defaults)


# ───────────────────────── overlay registration ─────────────────────────

def _split_comment(s):
    quote = None
    for i, ch in enumerate(s):
        if quote:
            if ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
        elif ch == "#" and (i == 0 or s[i - 1] in " \t"):
            return s[:i].rstrip(), s[i:]
    return s.rstrip(), ""


def _overlay_fm(text):
    return re.search(r"(?ms)^---[ \t]*\n(.*?)\n---[ \t]*(?:\n|$)", text)


def _registered_from_lines(lines):
    for i, line in enumerate(lines):
        m = re.match(r"^specimens:\s*(.*)$", line)
        if not m:
            continue
        value, comment = _split_comment(m.group(1))
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            items = [x.strip().strip("'\"") for x in value[1:-1].split(",") if x.strip()]
            end = i
        elif value:
            items, end = [value.strip("'\"")], i
        else:
            items, end = [], i
            j = i + 1
            while j < len(lines) and re.match(r"^\s+-\s*", lines[j]):
                items.append(re.sub(r"^\s+-\s*", "", lines[j]).strip().strip("'\""))
                end = j
                j += 1
        return i, end, items, comment
    return None


def register_in_overlay(overlay, slug):
    if not overlay.exists():
        overlay.parent.mkdir(parents=True, exist_ok=True)
        overlay.write_text(f"---\ntone: neutral\nspecimens: [{slug}]\n---\n", encoding="utf-8")
        return True
    text = overlay.read_text(encoding="utf-8")
    m = _overlay_fm(text)
    if not m:
        raise SystemExit(f"ds4a specimens: {overlay} has no YAML frontmatter")
    lines = m.group(1).split("\n")
    found = _registered_from_lines(lines)
    if found:
        i, end, items, comment = found
        if slug in items:
            return False
        items.append(slug)
        new = f"specimens: [{', '.join(items)}]" + (f"  {comment}" if comment else "")
        lines[i:end + 1] = [new]
    else:
        insert_at = len(lines)
        for i, line in enumerate(lines):
            if re.match(r"^(tone|type):", line):
                insert_at = i + 1
        lines.insert(insert_at, f"specimens: [{slug}]")
    body = text[:m.start(1)] + "\n".join(lines) + text[m.end(1):]
    overlay.write_text(body, encoding="utf-8")
    return True


def unregister_in_overlay(overlay, slug):
    if not overlay.exists():
        return False
    text = overlay.read_text(encoding="utf-8")
    m = _overlay_fm(text)
    if not m:
        return False
    lines = m.group(1).split("\n")
    found = _registered_from_lines(lines)
    if not found:
        return False
    i, end, items, comment = found
    if slug not in items:
        return False
    items.remove(slug)
    if items:
        new = f"specimens: [{', '.join(items)}]" + (f"  {comment}" if comment else "")
        lines[i:end + 1] = [new]
    else:
        del lines[i:end + 1]
    body = text[:m.start(1)] + "\n".join(lines) + text[m.end(1):]
    overlay.write_text(body, encoding="utf-8")
    return True


# ───────────────────────── commands ─────────────────────────

def scan(project, lib):
    specimens = load(project)
    covered = {R.norm(s["slug"]) for s in specimens}
    covered |= {R.norm(s["title"]) for s in specimens}
    covered |= {R.norm(s["contract"]) for s in specimens if s["contract"]}
    contracts = {R.norm(n) for n in contract_names(lib)}
    rows = []
    for root in CANDIDATE_ROOTS:
        base = project / root
        if not base.exists():
            continue
        for p in sorted(base.rglob("*")):
            if not p.is_file() or p.suffix not in CANDIDATE_EXTS:
                continue
            if any(part in SKIP_PARTS for part in p.parts):
                continue
            stem = p.stem
            if re.match(r"^(index|layout|page|template)(\.|$)", stem, re.I):
                continue
            if re.search(r"\.(test|spec|stories|story)$", stem, re.I):
                continue
            n = R.norm(stem)
            if n in covered or n in contracts:
                continue
            rows.append({"slug": kebab(stem), "title": pretty(kebab(stem)),
                         "path": p.relative_to(project).as_posix()})
    return rows


def add(args, project, lib):
    source = Path(args.source) if args.source else None
    if source and not source.is_absolute():
        source = project / source
    if not source and not args.html:
        print("ds4a specimens add: pass --from <component file> or --html <snippet file>", file=sys.stderr)
        return 1
    slug = kebab(args.name)
    if not slug:
        print(f"ds4a specimens add: invalid name {args.name!r}", file=sys.stderr)
        return 1
    folder = project / ".ds4a" / "specimens"
    out = folder / f"{slug}.html"
    if out.exists() and not args.force:
        print(f"ds4a specimens add: {out} exists (use --force to replace)", file=sys.stderr)
        return 1

    meta = {"title": args.title or pretty(slug), "captured": args.captured or date.today().isoformat()}
    if source:
        meta["source"] = source.resolve().relative_to(project.resolve()).as_posix()
    if args.contract:
        meta["contract"] = args.contract

    source_text = source.read_text(encoding="utf-8", errors="ignore") if source else ""
    if args.html:
        raw = Path(args.html).read_text(encoding="utf-8")
        old_meta, raw_body = parse_header(raw)
        for k, v in old_meta.items():
            meta.setdefault(k, v)
        meta["title"] = args.title or meta.get("title") or pretty(slug)
        if source:
            meta["source"] = source.resolve().relative_to(project.resolve()).as_posix()
        if args.contract:
            meta["contract"] = args.contract
        markup = raw_body.strip()
    else:
        defaults = {m.group(1): m.group(2)
                    for m in re.finditer(r"(\w+)\s*=\s*[\"']([^\"']*)[\"']", source_text)}
        markup = extract_markup(source_text, source.suffix.lower(), defaults)

    if not markup or "<" not in markup:
        markup = (f'<div class="specimen-placeholder">\n'
                  f'  <p>{meta["title"]} — replace this placeholder with the real markup.</p>\n</div>')
        print(f"ds4a specimens add: could not extract markup from {source}; wrote a placeholder", file=sys.stderr)

    folder.mkdir(parents=True, exist_ok=True)
    out.write_text(spec_header(meta) + "\n" + markup.rstrip() + "\n", encoding="utf-8")
    registered = register_in_overlay(project / ".ds4a" / "project.md", slug)
    print(f"wrote {out}" + (" (registered in .ds4a/project.md)" if registered else ""))
    if not args.no_build:
        build(project, lib)
    return 0


def remove(args, project, lib):
    slug = kebab(args.name)
    out = project / ".ds4a" / "specimens" / f"{slug}.html"
    if not out.exists():
        print(f"ds4a specimens remove: {out} does not exist", file=sys.stderr)
        return 1
    out.unlink()
    unregister_in_overlay(project / ".ds4a" / "project.md", slug)
    print(f"removed {out}")
    if not args.no_build:
        build(project, lib)
    return 0


def build(project, lib):
    cmd = [sys.executable, str(Path(__file__).resolve().parent / "build-preview.py"),
           "--project", str(project), "--library", str(lib)]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode:
        print(res.stderr.strip() or "ds4a specimens: preview build failed", file=sys.stderr)
        return
    print(res.stderr.strip())


def list_specimens(project):
    for s in load(project):
        bits = [f"{s['slug']}  {s['title']}"]
        if s["source"]:
            bits.append(f"source {s['source']}")
        if s["captured"]:
            bits.append(f"captured {s['captured']}")
        if s["contract"]:
            bits.append(f"contract {s['contract']}")
        if s["status"] in ("changed", "missing"):
            bits.append(f"WARNING source {s['status']}")
        print(" · ".join(bits))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project", default=".")
    ap.add_argument("--library", default=str(R.SKILL_DIR / "library"))
    sub = ap.add_subparsers(dest="cmd", required=True)
    p_list = sub.add_parser("list")
    p_scan = sub.add_parser("scan")
    p_scan.add_argument("--json", action="store_true")
    p_add = sub.add_parser("add")
    p_add.add_argument("name")
    p_add.add_argument("--from", dest="source", help="component file to capture")
    p_add.add_argument("--html", help="snippet file to use instead of extracting from source")
    p_add.add_argument("--title")
    p_add.add_argument("--contract", help="core contract this specimen is the project version of")
    p_add.add_argument("--captured", help="capture date (default: today)")
    p_add.add_argument("--force", action="store_true")
    p_add.add_argument("--no-build", action="store_true")
    p_remove = sub.add_parser("remove")
    p_remove.add_argument("name")
    p_remove.add_argument("--no-build", action="store_true")
    args = ap.parse_args()

    project, lib = Path(args.project), Path(args.library)
    try:
        if args.cmd == "list":
            list_specimens(project)
            return 0
        if args.cmd == "scan":
            rows = scan(project, lib)
            if args.json:
                print(json.dumps(rows, indent=2))
            elif not rows:
                print("No candidates: every component either has a specimen or matches a core contract.")
            else:
                print(f"{len(rows)} component{'s' if len(rows) != 1 else ''} with no specimen and no contract:")
                for r in rows:
                    print(f"  {r['slug']:<24} {r['path']}")
                print('\nCapture one: python3 scripts/specimens.py --project . add <slug> --from <path>')
            return 0
        if args.cmd == "add":
            return add(args, project, lib)
        if args.cmd == "remove":
            return remove(args, project, lib)
    except (OSError, R.ResolveError, ValueError) as e:
        print(f"ds4a specimens: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
