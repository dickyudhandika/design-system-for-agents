#!/usr/bin/env python3
"""ds4a apply — write the resolved tokens into one CSS file the project owns.

The layers stay the source of truth. This script only materializes them:

  <project>/src/styles/ds4a-tokens.css   (default, plain custom properties)
  <project>/src/styles/ds4a-theme.css    (--tailwind: one @theme block)

It never edits an existing component, Tailwind config, or stylesheet. If the
target file already exists it must carry the "Generated by ds4a apply" marker
or the write is refused (--force overrides, after the user confirms).

Usage:
  python3 scripts/apply.py --project .
  python3 scripts/apply.py --project . --tailwind
  python3 scripts/apply.py --project . --check       # drift report, writes nothing
  python3 scripts/apply.py --project . --check --strict

Standard library only.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import resolve as R  # noqa: E402

MARKER = "Generated by ds4a apply"
DEFAULT_OUT = "src/styles/ds4a-tokens.css"
THEME_OUT = "src/styles/ds4a-theme.css"
SCAN_ROOTS = ("src", "app", "components", "pages", "styles")
SCAN_EXTS = {".css", ".scss", ".sass", ".less", ".ts", ".tsx", ".js", ".jsx",
             ".astro", ".svelte", ".vue", ".html", ".mdx"}
SKIP_DIRS = {"node_modules", ".git", ".next", "dist", "build", ".ds4a", ".turbo", "coverage"}


def md_table(text, heading):
    """Rows of the markdown table under `### heading`: {name: (value, use)}."""
    m = re.search(rf"^### {re.escape(heading)}\s*$(.*?)(?=^#{{2,3}} |\Z)", text, re.M | re.S)
    rows = {}
    for line in (m.group(1) if m else "").split("\n"):
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 2 or set(cells[0]) <= set("-: ") or cells[0] == "Token":
            continue
        rows[cells[0].strip("`")] = (cells[1].strip("`"), cells[2] if len(cells) > 2 else "")
    return rows


def css_safe(s):
    return re.sub(r"[;{}<]", "", s)


def layer_texts(lib, tone, overlay):
    texts = [(lib / "tones" / f"{tone}.md").read_text(encoding="utf-8")]
    if overlay and Path(overlay).exists():
        texts.append(Path(overlay).read_text(encoding="utf-8"))
    return texts


def color_tokens(tree):
    return [(k, R.unquote(v.value)) for k, v in tree.get("colors", {}).items()
            if isinstance(v, R.Leaf)]


def spacing_tokens(tree):
    return [(k, R.unquote(v.value)) for k, v in tree.get("spacing", {}).items()
            if isinstance(v, R.Leaf)]


def radius_tokens(tree):
    return [(k, R.unquote(v.value)) for k, v in tree.get("rounded", {}).items()
            if isinstance(v, R.Leaf)]


def type_steps(tree):
    return [(n, {k: R.unquote(x.value) for k, x in v.items() if isinstance(x, R.Leaf)})
            for n, v in tree.get("typography", {}).items() if isinstance(v, dict)]


def families(tree):
    """First family of each typographic category: title, label, paragraph."""
    out = {}
    for n, spec in type_steps(tree):
        cat = n.split("-")[0]
        fam = spec.get("fontFamily")
        if fam and cat not in out:
            out[cat] = fam
    return out


def elevation_motion(texts):
    shadows, motion = {}, {}
    for t in texts:
        shadows.update(md_table(t, "Shadow tokens"))
        motion.update(md_table(t, "Motion tokens"))
    return shadows, motion


def expected_tokens(info, texts, tailwind=False):
    """Ordered {css custom property: value} for the current resolved system."""
    tree = info["tree"]
    out = {}
    for k, v in color_tokens(tree):
        out[f"--color-{k}"] = v
    if tailwind:
        for cat, fam in families(tree).items():
            out[f"--font-{cat}"] = fam
        for n, spec in type_steps(tree):
            out[f"--text-{n}"] = spec.get("fontSize", "16px")
            out[f"--text-{n}--line-height"] = spec.get("lineHeight", "normal")
            out[f"--text-{n}--letter-spacing"] = spec.get("letterSpacing", "normal")
            out[f"--text-{n}--font-weight"] = spec.get("fontWeight", "400")
    else:
        for n, spec in type_steps(tree):
            out[f"--text-{n}"] = spec.get("fontSize", "16px")
            out[f"--text-{n}--family"] = spec.get("fontFamily", "system-ui")
            out[f"--text-{n}--weight"] = spec.get("fontWeight", "400")
            out[f"--text-{n}--leading"] = spec.get("lineHeight", "normal")
            out[f"--text-{n}--tracking"] = spec.get("letterSpacing", "normal")
    for k, v in spacing_tokens(tree):
        out[f"--spacing-{k}"] = v
    for k, v in radius_tokens(tree):
        out[f"--radius-{k}"] = v
    shadows, motion = elevation_motion(texts)
    for n in ("subtle", "elevated"):
        if n in shadows:
            out[f"--shadow-{n}"] = shadows[n][0]
    for k in ("duration.fast", "duration.smooth"):
        if k in motion:
            out[f"--{k.replace('.', '-')}"] = motion[k][0]
    for k in ("ease.out", "ease.in-out"):
        if k in motion:
            out[f"--{k.replace('.', '-')}"] = motion[k][0]
    return out


def css_file(info, tokens, tailwind=False):
    lines = [f"/* {MARKER} — do not edit by hand.",
             f" * Layers: {info['layers']}",
             " * Regenerate: python3 scripts/apply.py --project ." + (" --tailwind" if tailwind else ""),
             " * Import once: @import \"./styles/%s\";" % ("ds4a-theme.css" if tailwind else "ds4a-tokens.css"),
             " */", ""]
    if tailwind:
        lines.append("@theme {")
    else:
        lines.append(":root {")
    group, names = None, {
        "--color-": "Color", "--font-": "Typography", "--text-": "Typography",
        "--spacing-": "Spacing", "--radius-": "Radius", "--shadow-": "Elevation",
        "--duration-": "Motion", "--ease-": "Motion",
    }
    for name, value in tokens.items():
        g = next((v for k, v in names.items() if name.startswith(k)), "Tokens")
        if g != group:
            if group is not None:
                lines.append("")
            lines.append(f"  /* {g} */")
            group = g
        lines.append(f"  {name}: {css_safe(value)};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def parse_css_vars(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return {m.group(1): m.group(2).strip()
            for m in re.finditer(r"(--[A-Za-z0-9_-]+)\s*:\s*([^;{}]+);", text)}


def norm_value(v):
    v = v.strip().lower()
    if re.fullmatch(r"#[0-9a-f]{3}", v):
        v = "#" + "".join(c * 2 for c in v[1:])
    if re.fullmatch(r"#[0-9a-f]{6}", v):
        v = v.upper()
    return re.sub(r"\s+", " ", v)


def scan_hardcoded(project, tokens):
    """Hardcoded values in source that exactly match a token value."""
    colors, sizes = {}, {}
    for name, value in tokens.items():
        nv = norm_value(value)
        if name.startswith("--color-") and re.fullmatch(r"#[0-9a-fA-F]{3,8}", nv):
            colors.setdefault(nv, []).append(name)
        if re.fullmatch(r"\d+(?:\.\d+)?px", nv) and name.startswith(("--spacing-", "--radius-", "--text-")):
            sizes.setdefault(nv, []).append(name)
    # Prefer semantic scale tokens over type sizes when one value matches both.
    priority = {"--spacing-": 0, "--radius-": 1, "--text-": 2}
    for names in sizes.values():
        names.sort(key=lambda n: next((p for k, p in priority.items() if n.startswith(k)), 9))
    hits = []
    for root in SCAN_ROOTS:
        base = project / root
        if not base.exists():
            continue
        for p in base.rglob("*"):
            if not p.is_file() or p.suffix not in SCAN_EXTS:
                continue
            if any(part in SKIP_DIRS for part in p.parts):
                continue
            try:
                text = p.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                continue
            if MARKER in text[:400]:
                continue  # our own generated token file is not a migration candidate
            lines = text.split("\n")
            for i, line in enumerate(lines, 1):
                for m in re.finditer(r"#[0-9a-fA-F]{3,8}\b", line):
                    nv = norm_value(m.group(0))
                    if nv in colors:
                        hits.append((p.relative_to(project), i, m.group(0), ", ".join(colors[nv][:3])))
                for m in re.finditer(r"(?<![\w-])(\d+(?:\.\d+)?px)\b", line):
                    nv = norm_value(m.group(1))
                    if nv in sizes:
                        hits.append((p.relative_to(project), i, m.group(1), ", ".join(sizes[nv][:3])))
    return hits


def check(project, out, tokens, strict=False):
    problems = 0
    if not out.exists():
        print(f"ds4a apply --check: {out} does not exist. Run apply without --check to create it.")
        return 1 if strict else 0
    text = out.read_text(encoding="utf-8")
    if MARKER not in text:
        print(f"ds4a apply --check: {out} exists but was not generated by ds4a apply.")
        problems += 1
    actual = parse_css_vars(text)
    for name, value in tokens.items():
        if name not in actual:
            print(f"missing: {name} (overlay says {value})")
            problems += 1
        elif norm_value(actual[name]) != norm_value(value):
            print(f"drift: {name} is {actual[name]} in {out.name}, overlay says {value}")
            problems += 1
    for name in actual:
        if name not in tokens:
            print(f"stale: {name} is in {out.name} but not in the resolved layers")
            problems += 1
    hits = scan_hardcoded(project, tokens)
    for path, line, value, token in hits:
        print(f"candidate: {path}:{line} uses {value}, which matches {token}")
    if not problems and not hits:
        print(f"ds4a apply --check: clean ({len(tokens)} tokens, no drift, no matching hardcoded values).")
    else:
        print(f"ds4a apply --check: {problems} drift/missing, {len(hits)} hardcoded candidates.")
    return 1 if strict and (problems or hits) else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project", default=".")
    ap.add_argument("--library", default=str(R.SKILL_DIR / "library"))
    ap.add_argument("--tone")
    ap.add_argument("--type", dest="ptype")
    ap.add_argument("--out", help=f"output path (default: {DEFAULT_OUT}; {THEME_OUT} with --tailwind)")
    ap.add_argument("--tailwind", action="store_true", help="emit one Tailwind v4 @theme block")
    ap.add_argument("--check", action="store_true", help="report drift and hardcoded candidates; write nothing")
    ap.add_argument("--strict", action="store_true", help="with --check: exit 1 on any drift or candidate")
    ap.add_argument("--force", action="store_true", help="overwrite an existing file not generated by ds4a")
    args = ap.parse_args()

    project = Path(args.project)
    lib = Path(args.library)
    overlay = project / ".ds4a" / "project.md"
    overlay = overlay if overlay.exists() else None
    tone, ptype = args.tone, args.ptype
    try:
        if overlay:
            ov_fm, _, _ = R.read_layer(overlay)
            tone = tone or R.leaf_text(ov_fm, "tone") or None
            ptype = ptype or R.leaf_text(ov_fm, "type") or None
        tone = tone or "neutral"
        _, info = R.resolve(lib, tone, overlay, ptype)
    except R.ResolveError as e:
        print(f"ds4a apply: {e}", file=sys.stderr)
        return 1

    tokens = expected_tokens(info, layer_texts(lib, tone, overlay), args.tailwind)
    out = Path(args.out) if args.out else project / (THEME_OUT if args.tailwind else DEFAULT_OUT)

    if args.check:
        return check(project, out, tokens, args.strict)

    if out.exists():
        text = out.read_text(encoding="utf-8")
        if MARKER not in text and not args.force:
            print(f"ds4a apply: {out} exists and was not generated by ds4a apply; refusing to overwrite (use --force)",
                  file=sys.stderr)
            return 1
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(css_file(info, tokens, args.tailwind), encoding="utf-8")
    try:
        rel = out.resolve().relative_to((project / "src").resolve()).as_posix()
        import_line = f'@import "./{rel}";'
    except ValueError:
        try:
            rel = out.resolve().relative_to(project.resolve()).as_posix()
            import_line = f'@import "{rel}";'
        except ValueError:
            import_line = f'@import "{out}";'
    print(f"wrote {out} ({len(tokens)} tokens)")
    print(f"→ add once, from a CSS file in src/: {import_line}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
